"""Rubric-generic visual observation and assessment adapter."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import vlm_assessment


def run_assessment(
    *,
    video: Path,
    perception: dict[str, Any],
    rubric_path: Path,
    output_dir: Path,
    observation_endpoint: Any,
    assessment_endpoint: Any,
    audio_evidence: dict[str, Any],
    observation_workers: int,
    frames_per_event: int,
    max_image_side: int,
    image_detail: str,
    confidence_threshold: float,
    assessment_policy: str,
    assessment_images: str,
    assessment_image_confidence_threshold: float,
    assessment_visual_override_confidence: float,
    assessment_visual_override_margin: float,
    assessment_images_per_criterion: int,
    assessment_context_frames: int,
    critical_criterion_images: int,
    assessment_image_workers: int,
    assessment_rescue_images: int,
    criterion_localization: bool,
    localization_candidates: int,
    localization_coarse_seconds: float,
    localization_search_radius: float,
    localization_refinement_fps: float,
    localization_evidence_images: int,
    localization_confidence_threshold: float,
    localization_workers: int,
    retries: int,
    resume: bool,
) -> dict[str, Any]:
    return vlm_assessment.run_vlm_assessment(
        raw_video=video,
        perception=perception,
        rubric_path=rubric_path,
        output_dir=output_dir,
        observation_api_key=observation_endpoint.api_key,
        observation_provider=observation_endpoint.provider,
        observation_base_url=observation_endpoint.base_url,
        observation_model=observation_endpoint.model,
        assessment_api_key=assessment_endpoint.api_key,
        assessment_provider=assessment_endpoint.provider,
        assessment_base_url=assessment_endpoint.base_url,
        assessment_model=assessment_endpoint.model,
        frames_per_event=frames_per_event,
        max_image_side=max_image_side,
        confidence_threshold=confidence_threshold,
        assessment_policy=assessment_policy,
        assessment_images=assessment_images,
        assessment_image_confidence_threshold=assessment_image_confidence_threshold,
        assessment_visual_override_confidence=assessment_visual_override_confidence,
        assessment_visual_override_margin=assessment_visual_override_margin,
        assessment_images_per_criterion=assessment_images_per_criterion,
        assessment_context_frames=assessment_context_frames,
        critical_criterion_images=critical_criterion_images,
        assessment_image_workers=assessment_image_workers,
        assessment_rescue_images=assessment_rescue_images,
        criterion_localization=criterion_localization,
        localization_candidates=localization_candidates,
        localization_coarse_seconds=localization_coarse_seconds,
        localization_search_radius=localization_search_radius,
        localization_refinement_fps=localization_refinement_fps,
        localization_evidence_images=localization_evidence_images,
        localization_confidence_threshold=localization_confidence_threshold,
        localization_workers=localization_workers,
        retries=retries,
        resume=resume,
        image_detail=image_detail,
        audio_evidence=audio_evidence,
        observation_workers=observation_workers,
    )
